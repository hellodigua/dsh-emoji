import { execFileSync } from 'node:child_process'
import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { basename, resolve } from 'node:path'

const cliArguments = process.argv.slice(2)
if (cliArguments[0] === '--') cliArguments.shift()
const [sourceArgument, sourceRevision] = cliArguments
if (sourceArgument === undefined || !/^[0-9a-f]{40}$/.test(sourceRevision ?? '')) {
  throw new Error('usage: node scripts/sync-bilibili-assets.mjs <emoji-repo> <40-char-source-revision>')
}

const projectRoot = resolve(import.meta.dirname, '..')
const sourceRoot = resolve(sourceArgument)
const sourceCatalogPath = resolve(sourceRoot, 'emoji.json')
const targetAssetRoot = resolve(projectRoot, 'assets/emoji/bilibili')
const targetCatalogPath = resolve(projectRoot, 'src/catalog.generated.ts')
const actualRevision = execFileSync('git', ['-C', sourceRoot, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim()
if (actualRevision !== sourceRevision) {
  throw new Error(`emoji source revision mismatch: expected ${sourceRevision}, received ${actualRevision}`)
}
const sourceChanges = execFileSync(
  'git', ['-C', sourceRoot, 'status', '--porcelain', '--', 'emoji.json', 'output/bilibili'], { encoding: 'utf8' },
).trim()
if (sourceChanges.length > 0) {
  throw new Error('emoji source has uncommitted changes in emoji.json or output/bilibili')
}
const raw = JSON.parse(await readFile(sourceCatalogPath, 'utf8'))
if (!Array.isArray(raw)) throw new Error('emoji.json root must be an array')

const platform = raw.find(row => row?.platform === 'bilibili')
if (platform === undefined || !Array.isArray(platform.emojis)) {
  throw new Error('emoji.json does not contain a bilibili emoji array')
}

const entries = platform.emojis.map((value, index) => {
  if (typeof value !== 'object' || value === null) throw new Error(`bilibili emoji ${index} must be an object`)
  const { url, name, tags, keywords } = value
  if (typeof url !== 'string' || !/^output\/bilibili\/bl_\d{2}\.avif$/.test(url)) {
    throw new Error(`bilibili emoji ${index} has an invalid url`)
  }
  if (typeof name !== 'string' || name.length === 0) throw new Error(`bilibili emoji ${index} has an invalid name`)
  if (!Array.isArray(tags) || tags.some(tag => typeof tag !== 'string')) throw new Error(`bilibili emoji ${index} has invalid tags`)
  if (!Array.isArray(keywords) || keywords.length === 0 || keywords.some(keyword => typeof keyword !== 'string')) {
    throw new Error(`bilibili emoji ${index} has invalid keywords`)
  }
  const file = basename(url)
  return {
    id: `bilibili:${file.slice(0, -'.avif'.length)}`,
    platform: 'bilibili',
    name,
    file,
    tags,
    keywords,
    sourcePath: url,
  }
})

if (entries.length !== 35) throw new Error(`expected 35 bilibili emojis, received ${entries.length}`)
for (const field of ['id', 'file']) {
  const values = entries.map(entry => entry[field])
  if (new Set(values).size !== values.length) throw new Error(`duplicate bilibili emoji ${field}`)
}

await rm(targetAssetRoot, { force: true, recursive: true })
await mkdir(targetAssetRoot, { recursive: true })
for (const entry of entries) {
  await copyFile(resolve(sourceRoot, entry.sourcePath), resolve(targetAssetRoot, entry.file))
}

const generatedEntries = entries.map(({ sourcePath: _sourcePath, ...entry }) => entry)
const source = `/** Generated by scripts/sync-bilibili-assets.mjs. Do not edit manually. */

export interface EmojiCatalogEntry {
  readonly id: string
  readonly platform: 'bilibili'
  readonly name: string
  readonly file: string
  readonly tags: readonly string[]
  readonly keywords: readonly string[]
}

export const CATALOG_SOURCE_REVISION = ${JSON.stringify(sourceRevision)}

export const EMOJIS = ${JSON.stringify(generatedEntries, null, 2)} as const satisfies readonly EmojiCatalogEntry[]
`
await writeFile(targetCatalogPath, source)

process.stdout.write(`synced ${entries.length} bilibili emojis from ${sourceRevision}\n`)
